/**
 * Google Maps input parsing. Staff paste either:
 *  - the "Embed a map" iframe code, or its src (https://www.google.com/maps/embed?pb=…)
 *  - a Google Maps link from the address bar (…/maps/place/Name/@lat,lng,17z/…)
 *  - a share link (https://maps.app.goo.gl/… or goo.gl/maps/…) → resolved on the server first
 *  - plain "lat, lng" coordinates
 * Only Google Maps embed URLs are ever stored as the iframe src.
 */

export interface MapParseResult {
	embedUrl?: string;
	directionsUrl?: string;
	latitude?: number;
	longitude?: number;
	/** Short link that must be expanded (server-side fetch) before parsing. */
	needsResolve?: boolean;
	error?: string;
}

const EMBED_PREFIX = 'https://www.google.com/maps/embed?';
const SHORT_LINK = /^https:\/\/(maps\.app\.goo\.gl|goo\.gl\/maps|g\.co\/kgs)\//i;
const GOOGLE_MAPS_HOST = /^(www\.)?google\.[a-z.]{2,6}$|^maps\.google\.[a-z.]{2,6}$/i;

/** Is this a URL we allow as a map iframe src? */
export function isAllowedEmbedUrl(url: string | null | undefined): boolean {
	if (!url) return false;
	let u: URL;
	try {
		u = new URL(url);
	} catch {
		return false;
	}
	if (u.protocol !== 'https:' || u.hostname !== 'www.google.com') return false;
	if (u.pathname === '/maps/embed' && (u.searchParams.has('pb') || u.searchParams.has('q'))) return true;
	// Key-less coordinate embed generated by coordsEmbedUrl()
	return u.pathname === '/maps' && u.searchParams.get('output') === 'embed' && u.searchParams.has('q');
}

export function coordsEmbedUrl(lat: number, lng: number, zoom = 16): string {
	return `https://www.google.com/maps?q=${lat},${lng}&z=${zoom}&output=embed`;
}

export function directionsUrlFor(lat: number, lng: number): string {
	return `https://www.google.com/maps/dir/?api=1&destination=${lat},${lng}`;
}

function validCoords(lat: number, lng: number) {
	return Number.isFinite(lat) && Number.isFinite(lng) && Math.abs(lat) <= 90 && Math.abs(lng) <= 180 && !(lat === 0 && lng === 0);
}

function round(n: number) {
	return Math.round(n * 1e7) / 1e7;
}

function decodeEntities(s: string) {
	return s.replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#39;/g, "'");
}

/** Extract coordinates from any Google Maps URL format we know about. */
export function coordsFromUrl(url: string): { lat: number; lng: number } | null {
	const tries: RegExp[] = [
		/!3d(-?\d+(?:\.\d+)?)!4d(-?\d+(?:\.\d+)?)/, // place pin (lat, lng)
		/@(-?\d+(?:\.\d+)?),(-?\d+(?:\.\d+)?)(?:,[\d.]+[zm])?/, // viewport centre
		/[?&](?:q|query|ll|destination|center)=(-?\d+(?:\.\d+)?)(?:,|%2C)\s*(-?\d+(?:\.\d+)?)/i
	];
	for (const re of tries) {
		const m = re.exec(url);
		if (m) {
			const lat = Number(m[1]);
			const lng = Number(m[2]);
			if (validCoords(lat, lng)) return { lat: round(lat), lng: round(lng) };
		}
	}
	// Embed "pb" parameter: !2d<lng>!3d<lat>
	const pb = /!2d(-?\d+(?:\.\d+)?)!3d(-?\d+(?:\.\d+)?)/.exec(url);
	if (pb) {
		const lat = Number(pb[2]);
		const lng = Number(pb[1]);
		if (validCoords(lat, lng)) return { lat: round(lat), lng: round(lng) };
	}
	return null;
}

export function parseMapInput(raw: string): MapParseResult {
	const input = decodeEntities(raw.trim());
	if (!input) return { error: 'Paste a Google Maps link or embed code.' };

	// 1. Plain coordinates
	const plain = /^\s*(-?\d{1,2}(?:\.\d+)?)\s*,\s*(-?\d{1,3}(?:\.\d+)?)\s*$/.exec(input);
	if (plain) {
		const lat = Number(plain[1]);
		const lng = Number(plain[2]);
		if (!validCoords(lat, lng)) return { error: 'Those coordinates are out of range.' };
		return { latitude: lat, longitude: lng, embedUrl: coordsEmbedUrl(lat, lng), directionsUrl: directionsUrlFor(lat, lng) };
	}

	// 2. iframe code → take its src
	let url = input;
	if (/<iframe/i.test(input)) {
		const m = /\ssrc\s*=\s*["']([^"']+)["']/i.exec(input);
		if (!m) return { error: 'Could not find the map address (src) in the embed code.' };
		url = decodeEntities(m[1]);
		if (!url.startsWith(EMBED_PREFIX)) return { error: 'Only Google Maps embed codes are allowed.' };
	}

	let u: URL;
	try {
		u = new URL(url);
	} catch {
		return { error: 'That does not look like a link. Paste the full Google Maps link or embed code.' };
	}
	if (u.protocol !== 'https:') return { error: 'The link must start with https://' };

	// 3. Short share links need to be expanded on the server.
	if (SHORT_LINK.test(url)) return { needsResolve: true };

	if (!GOOGLE_MAPS_HOST.test(u.hostname) || !(u.pathname.startsWith('/maps') || u.hostname.startsWith('maps.'))) {
		return { error: 'Only Google Maps links are supported.' };
	}

	const coords = coordsFromUrl(url);

	// 4. Official embed URL
	if (url.startsWith(EMBED_PREFIX)) {
		return {
			embedUrl: url,
			latitude: coords?.lat,
			longitude: coords?.lng,
			directionsUrl: coords ? directionsUrlFor(coords.lat, coords.lng) : undefined
		};
	}

	// 5. Regular maps link
	if (coords) {
		return {
			latitude: coords.lat,
			longitude: coords.lng,
			embedUrl: coordsEmbedUrl(coords.lat, coords.lng),
			directionsUrl: directionsUrlFor(coords.lat, coords.lng)
		};
	}

	// A place/search link without coordinates: embed by query text.
	const query =
		u.searchParams.get('q') ??
		u.searchParams.get('query') ??
		/\/maps\/(?:place|search)\/([^/@]+)/.exec(u.pathname)?.[1]?.replace(/\+/g, ' ');
	if (query) {
		const q = decodeURIComponent(query);
		return {
			embedUrl: `https://www.google.com/maps?q=${encodeURIComponent(q)}&output=embed`,
			directionsUrl: `https://www.google.com/maps/dir/?api=1&destination=${encodeURIComponent(q)}`
		};
	}
	return { error: 'Could not find a location in that link. Try the "Embed a map" code instead.' };
}
